type Vars = Record<string, string | number>

export function translate(lang: LocaleCode, key: string, vars?: Vars): string {
  const entry = (messages as Record<string, Partial<Record<LocaleCode, string>>>)[key]
  let text = entry?.[lang] ?? entry?.nl ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

